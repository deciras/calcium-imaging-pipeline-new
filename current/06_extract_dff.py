    parser = argparse.ArgumentParser(description="Extract neuropil-corrected dF/F traces from suite2p outputs.")
    parser.add_argument("--data-root", type=Path, required=True, help="Original data root.")
    parser.add_argument("--input-root", type=Path, help="Step-05 suite2p root. Default: OUTPUT_ROOT/05_suite2p_roi_detection.")
    parser.add_argument("--output-root", type=Path, help="Pipeline output root. Default: DATA_ROOT.")
    parser.add_argument("--curated-root", type=Path, help="Step-05c curated ROI root. Default: OUTPUT_ROOT/05c_roi_quality_filter.")
    parser.add_argument("--action", choices=("skip", "overwrite"), default="skip", help="Existing-output behavior.")
    parser.add_argument("--dry-run", action="store_true", help="Print work plan without reading suite2p arrays or writing files.")
    parser.add_argument(
        "--roi-source",
        choices=("auto", "curated", "suite2p", "all"),
        default="auto",
        help="ROI selection source. auto uses 05c curated labels when present, otherwise suite2p iscell.",
    )
    parser.add_argument("--include-noncell", action="store_true", help="Keep all suite2p ROIs instead of only iscell==1.")
    parser.add_argument("--neuropil-coeff", type=float, default=0.7, help="Coefficient for suite2p Fneu subtraction.")
    parser.add_argument(
        "--f0-mode",
        choices=("percentile", "rolling-percentile", "rolling-median", "stim-baseline"),
        default="percentile",
        help="F0 estimation method.",
    )
    parser.add_argument("--f0-percentile", type=float, default=10.0, help="Percentile used by percentile-based F0 modes.")
    parser.add_argument("--f0-window-sec", type=float, default=60.0, help="Rolling F0 window size in seconds.")
    parser.add_argument("--f0-eps", type=float, default=1e-6, help="Minimum denominator for dF/F.")
    parser.add_argument("--default-fps", type=float, default=2.0, help="Fallback fps when metadata and ops are missing.")
