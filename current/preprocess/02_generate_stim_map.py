def estimate_trial_start_from_raw_file(raw_oir_path: Path | None, timepoints: int, dt: float) -> datetime | None:
    if raw_oir_path is None or not raw_oir_path.exists() or timepoints <= 0 or dt <= 0:
        return None
    modified_time = datetime.fromtimestamp(raw_oir_path.stat().st_mtime)
    return modified_time - timedelta(seconds=timepoints * dt)


def estimate_trial_start_from_metadata(meta: dict, raw_oir_path: Path | None, timepoints: int, dt: float) -> datetime | None:
    acquisition_time = meta.get("acquisition", {}).get("start_time")
    parsed_time = parse_host_datetime(acquisition_time)
    if parsed_time is not None:
        # The stimulus controller logs are local timestamps without timezone.
        # Drop timezone info after parsing so both clocks can be compared.
        return parsed_time.replace(tzinfo=None)

    return estimate_trial_start_from_raw_file(raw_oir_path, timepoints, dt)


def estimate_precise_boundary(
    brightness_trace: np.ndarray,
    frame_idx: int,
    baseline: float,
    peak: float,
    is_start: bool,
) -> float:
    if frame_idx < 0 or frame_idx >= len(brightness_trace):
        return 0.0 if is_start else 1.0

    brightness = brightness_trace[frame_idx]
    if peak - baseline > 0:
        ratio = (brightness - baseline) / (peak - baseline)
        ratio = np.clip(ratio, 0.0, 1.0)
    else:
        ratio = 0.5

    return float(1.0 - ratio) if is_start else float(ratio)


def analyze_stim_blocks(
    brightness_trace: np.ndarray,
    dt: float,
    dynamic_thresh: float,
    baseline: float,
    peak: float,
) -> list[dict]:
    is_stim_on = brightness_trace > dynamic_thresh
    stim_indices = np.where(is_stim_on)[0]
    if len(stim_indices) == 0:
        return []

    diffs = np.diff(stim_indices)
    split_points = np.where(diffs > 1)[0] + 1
    blocks = np.split(stim_indices, split_points)

    stim_blocks: list[dict] = []
    for block_idx, block in enumerate(blocks):
        if len(block) == 0:
            continue

        start_frame = int(block[0])
        end_frame = int(block[-1])
        start_offset = estimate_precise_boundary(
            brightness_trace, start_frame, baseline, peak, is_start=True
        )
        end_offset = estimate_precise_boundary(
            brightness_trace, end_frame, baseline, peak, is_start=False
        )
        start_time = (start_frame + start_offset) * dt
        end_time = (end_frame + end_offset) * dt

        stim_blocks.append(
            {
                "stim_index": block_idx + 1,
                "start_frame": start_frame,
                "end_frame": end_frame,
                "start_time_sec": round(float(start_time), 3),
                "end_time_sec": round(float(end_time), 3),
                "duration_sec": round(float(end_time - start_time), 3),
            }
        )
    return stim_blocks


def raw_stim_manifest(raw_stim_dir: Path | None) -> dict:
    if raw_stim_dir is None:
        return {}
    manifest_path = raw_stim_dir / "manifest.json"
    if not manifest_path.exists():
        return {}
    with manifest_path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def raw_stim_complete(raw_stim_dir: Path | None) -> bool:
    manifest = raw_stim_manifest(raw_stim_dir)
    if not manifest or raw_stim_dir is None:
        return False
    expected = int(manifest.get("file_count", manifest.get("frame_count", 0)) or 0)
    if expected <= 0:
        return False
    return len(sorted(raw_stim_dir.glob("t*.tif"))) >= expected


def read_projected_analog_trace(stim_path: Path) -> AnalogTrace:
    with tiff.TiffFile(stim_path) as tif:
        images = tif.asarray()
    if images.ndim == 2:
        trace = np.asarray([float(np.nanmean(images))], dtype=float)
    elif images.ndim == 3:
        trace = np.nanmean(images, axis=(1, 2)).astype(float)
    else:
        trace = np.nanmean(images.reshape((images.shape[0], -1)), axis=1).astype(float)
    return AnalogTrace(trace=trace, source="projected_stim_analog_tif")


def read_raw_analog_trace(raw_stim_dir: Path, raw_z_strategy: str) -> AnalogTrace:
    manifest = raw_stim_manifest(raw_stim_dir)
    files = sorted(raw_stim_dir.glob("t*.tif"))
    expected = int(manifest.get("file_count", manifest.get("frame_count", len(files))) or len(files))
    if expected > 0 and len(files) < expected:
        raise RuntimeError(
            "Raw stim analog folder is incomplete: {} has {} tif files, expected {}".format(
                raw_stim_dir, len(files), expected
            )
        )
    if not files:
        raise RuntimeError("Raw stim analog folder has no t*.tif files: {}".format(raw_stim_dir))

    per_z_rows: list[np.ndarray] = []
    for index, path in enumerate(files):
        if index == 0 or (index + 1) == len(files) or (index + 1) % 200 == 0:
            LOGGER.debug("正在读取原始刺激模拟信号 %s（%d/%d）", path.name, index + 1, len(files))
        arr = tiff.imread(path)
        if arr.ndim == 2:
            z_means = np.asarray([float(np.nanmean(arr))], dtype=float)
        else:
            z_means = np.nanmean(arr.reshape((arr.shape[0], -1)), axis=1).astype(float)
        per_z_rows.append(z_means)

    per_z = np.vstack(per_z_rows)
    if raw_z_strategy == "planes":
        trace = per_z.reshape(-1)
        n_z = int(per_z.shape[1]) if per_z.ndim == 2 and per_z.shape[1] > 0 else 1
        return AnalogTrace(
            trace=trace,
            source="raw_stim_analog_z_plane_sequence",
            raw_z_strategy=raw_z_strategy,
            dt_scale=1.0 / float(n_z),
        )

    if raw_z_strategy == "mean":
        trace = np.nanmean(per_z, axis=1)
        return AnalogTrace(trace=trace, source="raw_stim_analog_z_mean", raw_z_strategy=raw_z_strategy)

    if raw_z_strategy == "max":
        trace = np.nanmax(per_z, axis=1)
        return AnalogTrace(trace=trace, source="raw_stim_analog_z_max", raw_z_strategy=raw_z_strategy)

    z_ranges = np.nanpercentile(per_z, 95, axis=0) - np.nanpercentile(per_z, 5, axis=0)
    z_index = int(np.nanargmax(z_ranges))
    trace = per_z[:, z_index]
    return AnalogTrace(
        trace=trace,
        source="raw_stim_analog_best_z",
        raw_z_index=z_index + 1,
        raw_z_strategy="max-range",
    )


def read_analog_trace(trial: TrialInput, analog_source: str, raw_z_strategy: str) -> AnalogTrace:
    if analog_source in ("auto", "raw") and raw_stim_complete(trial.raw_stim_dir):
        assert trial.raw_stim_dir is not None
        return read_raw_analog_trace(trial.raw_stim_dir, raw_z_strategy)

    if analog_source == "raw":
        raise RuntimeError("Raw stim analog requested but complete raw folder is missing for {}".format(trial.trial_id))

    return read_projected_analog_trace(trial.stim_path)


def make_time_windows(total_time: float, preferred_window_sec: float) -> list[tuple[float, float]]:
    total_time = max(float(total_time), 1.0)
    preferred_window_sec = max(float(preferred_window_sec), 1.0)
    if total_time <= preferred_window_sec:
        return [(0.0, total_time)]
    windows = []
    start = 0.0
    while start < total_time:
        end = min(total_time, start + preferred_window_sec)
        windows.append((start, end))
        start = end
    return windows


def choose_plot_window_sec(total_time: float, n_events: int, has_pulses: bool) -> float:
    if total_time <= 180:
        return max(total_time, 1.0)
    if has_pulses:
        return 60.0
    if n_events >= 12:
        return 90.0
    return 120.0


def single_axis_fig_width(total_time: float) -> float:
    return min(max(14.0, float(total_time) / 18.0), 48.0)


def angle_sort_key(angle: str) -> tuple[int, float | str]:
    value = _as_float_or_none(angle)
    if value is None:
        return (1, str(angle))
    return (0, value)


def angle_to_color(angle: object):
    value = _as_float_or_none(angle)
    if value is None:
        return "0.45"
    normalized = (value % 180.0) / 180.0
    if abs(value % 180.0) < 1e-9 and value > 0:
        normalized = 1.0
    return plt.get_cmap("hsv")(0.72 * normalized)


def angle_label(angle: object) -> str:
    value = _as_float_or_none(angle)
    if value is None:
        return str(angle)
    if abs(value - round(value)) < 1e-6:
        return f"{int(round(value))} deg"
    return f"{value:g} deg"


def collect_angle_handles(angles: set[str]):
    handles = []
    for angle in sorted(angles, key=angle_sort_key):
        handles.append(
            plt.Line2D([0], [0], color=angle_to_color(angle), lw=6, label=angle_label(angle))
        )
    return handles


def add_angle_color_wheel(ax) -> None:
    inset = ax.inset_axes([0.86, 1.03, 0.12, 0.22])
    n_steps = 36
    for idx in range(n_steps):
        start = 180.0 * idx / n_steps
        end = 180.0 * (idx + 1) / n_steps
        mid_angle = (start + end) / 2.0
        inset.add_patch(
            Wedge(
                (0.0, 0.0),
                1.0,
                start,
                end,
                width=0.28,
                facecolor=angle_to_color(mid_angle),
                edgecolor="none",
            )
        )
    inset.text(1.05, -0.04, "0", ha="left", va="center", fontsize=7)
    inset.text(0.0, 1.08, "90", ha="center", va="bottom", fontsize=7)
    inset.text(-1.05, -0.04, "180", ha="right", va="center", fontsize=7)
    inset.text(0.0, -0.34, "angle color", ha="center", va="top", fontsize=7)
    inset.set_xlim(-1.15, 1.15)
    inset.set_ylim(-0.38, 1.15)
    inset.set_aspect("equal")
    inset.axis("off")


def add_figure_notes(ax, lines: list[str]) -> None:
    lines = [line for line in lines if str(line).strip()]
    if not lines:
        return
    ax.text(
        0.012,
        0.965,
        "\n".join(lines),
        transform=ax.transAxes,
        ha="left",
        va="top",
        fontsize=8,
        linespacing=1.25,
        bbox={
            "boxstyle": "round,pad=0.28",
            "facecolor": "white",
            "edgecolor": "0.75",
            "alpha": 0.82,
            "linewidth": 0.6,
        },
    )


def save_figure_with_pdf(fig, output_path: Path, dpi: int = 150) -> None:
    """
    Save a quick-preview PNG and an editable vector PDF for the same figure.
    """
    fig.savefig(output_path, dpi=dpi, bbox_inches="tight")
