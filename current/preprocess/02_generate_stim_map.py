def plot_stim_trace(
    brightness_trace: np.ndarray,
    time_axis: np.ndarray,
    stim_blocks: list[dict],
    dynamic_thresh: float | None,
    trial_id: str,
    output_path: Path,
    has_pulses: bool = False,
    figure_notes: list[str] | None = None,
) -> None:
    total_time = time_axis[-1] if len(time_axis) > 0 else 1
    fig, ax = plt.subplots(1, 1, figsize=(single_axis_fig_width(total_time), 4.2))

    y_min = float(np.nanmin(brightness_trace)) if len(brightness_trace) else 0.0
    y_max = float(np.nanmax(brightness_trace)) if len(brightness_trace) else 1.0
    y_pad = max((y_max - y_min) * 0.08, 1.0)

    local_time = time_axis
    local_trace = brightness_trace
    max_points = 20000
    if len(local_trace) > max_points:
        downsample_factor = len(local_trace) // max_points + 1
        local_time = local_time[::downsample_factor]
        local_trace = local_trace[::downsample_factor]
    ax.plot(local_time, local_trace, "b-", linewidth=0.8, label="Voltage/brightness", alpha=0.75)

    if dynamic_thresh is not None:
        ax.axhline(
            y=dynamic_thresh,
            color="r",
            linestyle="--",
            linewidth=0.9,
            label=f"Threshold ({dynamic_thresh:.1f})",
        )

    angle_values: set[str] = set()
    for block in stim_blocks:
        block_start = _as_float_or_none(block.get("start_time_sec"))
        block_end = _as_float_or_none(block.get("end_time_sec"))
        if block_start is None or block_end is None:
            continue
        angle = str(block.get("pol_angle", ""))
        if angle != "":
            angle_values.add(angle)
        ax.axvspan(
            block_start,
            block_end,
            alpha=0.22,
            color=angle_to_color(angle),
        )
        if len(stim_blocks) <= 80:
            mid_t = (block_start + block_end) / 2
            ax.text(mid_t, y_max + y_pad * 0.15, f"#{block['stim_index']}", ha="center", va="bottom", fontsize=7)

    ax.set_xlim(0, total_time)
    ax.set_ylim(y_min - y_pad, y_max + y_pad)
    ax.set_xlabel("Time (sec)", fontsize=11)
    ax.set_ylabel("a.u.", fontsize=9)
    ax.set_title(f"Stimulus Voltage Trace - {trial_id}", fontsize=12, fontweight="bold")
    ax.grid(True, alpha=0.25)
    add_figure_notes(ax, figure_notes or [])

    handles, labels = ax.get_legend_handles_labels()
    angle_handles = collect_angle_handles(angle_values)
    if angle_handles:
        handles.extend(angle_handles)
        add_angle_color_wheel(ax)
    if handles:
        ax.legend(
            handles=handles,
            loc="lower left",
            bbox_to_anchor=(0.0, 1.02),
            fontsize=8,
            ncol=min(8, len(handles)),
            frameon=False,
        )
    plt.tight_layout()
    try:
        save_figure_with_pdf(fig, output_path, dpi=150)
    finally:
        plt.close(fig)


def _as_float_or_none(value: object) -> float | None:
    if value is None or value == "":
        return None
    try:
        if pd.isna(value):
            return None
    except TypeError:
        pass
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def plot_stim_schematic(
    events_rows: list[dict],
    pulse_events_rows: list[dict],
    stim_blocks: list[dict],
    trial_id: str,
    output_path: Path,
    figure_notes: list[str] | None = None,
) -> None:
    if not events_rows and not pulse_events_rows and not stim_blocks:
        return

    has_pulses = bool(pulse_events_rows)
    onset_values = []
    offset_values = []
    for row in events_rows:
        onset_values.append(_as_float_or_none(row.get("start_time_sec")))
        offset_values.append(_as_float_or_none(row.get("end_time_sec")))
    for row in pulse_events_rows:
        onset_values.append(_as_float_or_none(row.get("analog_anchored_pulse_onset_sec")))
        offset_values.append(_as_float_or_none(row.get("analog_anchored_pulse_offset_sec")))
    for block in stim_blocks:
        onset_values.append(_as_float_or_none(block.get("start_time_sec")))
        offset_values.append(_as_float_or_none(block.get("end_time_sec")))

    onset_values = [value for value in onset_values if value is not None]
    offset_values = [value for value in offset_values if value is not None]
    if not onset_values or not offset_values:
        return

    total_time = max(offset_values) + 5.0
    fig_height = 3.5 if has_pulses else 2.7
    fig, ax = plt.subplots(1, 1, figsize=(single_axis_fig_width(total_time), fig_height))
    angle_values: set[str] = set()

    for row in events_rows:
        onset = _as_float_or_none(row.get("start_time_sec"))
        offset = _as_float_or_none(row.get("end_time_sec"))
        if onset is None or offset is None or offset <= onset:
            continue
        angle = str(row.get("pol_angle", ""))
        if angle != "":
            angle_values.add(angle)
        ax.broken_barh(
            [(onset, offset - onset)],
            (0.12, 0.24),
            facecolors=angle_to_color(angle),
            edgecolors=angle_to_color(angle),
            alpha=0.58,
        )
        stim_index = row.get("stim_index", "")
        mid = (onset + offset) / 2
        if stim_index != "" and len(events_rows) <= 80:
            ax.text(mid, 0.42, str(stim_index), ha="center", va="bottom", fontsize=7)

    for row in pulse_events_rows:
        onset = _as_float_or_none(row.get("analog_anchored_pulse_onset_sec"))
        offset = _as_float_or_none(row.get("analog_anchored_pulse_offset_sec"))
        if onset is None or offset is None or offset <= onset:
            continue
        angle = str(row.get("pol_angle", ""))
        if angle != "":
            angle_values.add(angle)
        ax.broken_barh(
            [(onset, offset - onset)],
            (0.58, 0.30),
            facecolors=angle_to_color(angle),
            edgecolors=angle_to_color(angle),
            alpha=0.95,
            linewidth=0.45,
        )

    if has_pulses:
        labeled_stims: set[int] = set()
        for row in pulse_events_rows:
            if int(row.get("pulse_index", 0) or 0) != 1:
                continue
            stim_index = int(row.get("stim_index", 0) or 0)
            if stim_index in labeled_stims:
                continue
            onset = _as_float_or_none(row.get("analog_anchored_pulse_onset_sec"))
            if onset is None:
                continue
            labeled_stims.add(stim_index)
            if len(labeled_stims) <= 80:
                ax.text(onset, 0.93, str(stim_index), ha="center", va="bottom", fontsize=7, rotation=90)

    ax.set_xlim(0, total_time)
    ax.set_ylim(0, 1.05)
    if has_pulses:
        ax.set_yticks([0.24, 0.73])
        ax.set_yticklabels(["packet", "flash"])
    else:
        ax.set_yticks([0.24])
        ax.set_yticklabels(["stim"])
    ax.set_xlabel("Time (sec)", fontsize=11)
    ax.set_title(f"Stimulus Timing Schematic - {trial_id}", fontsize=12, fontweight="bold")
    ax.grid(True, axis="x", alpha=0.25)
    add_figure_notes(ax, figure_notes or [])

    angle_handles = collect_angle_handles(angle_values)
    if angle_handles:
        add_angle_color_wheel(ax)
        ax.legend(
            handles=angle_handles,
            loc="lower left",
            bbox_to_anchor=(0.0, 1.02),
            fontsize=8,
            ncol=min(8, len(angle_handles)),
            frameon=False,
        )

    plt.tight_layout()
    try:
        save_figure_with_pdf(fig, output_path, dpi=150)
    finally:
        plt.close(fig)


def build_summary_row(
    trial_id: str,
    protocol: StimProtocol | None,
    protocol_match_delta_sec: float | None,
    trial_start_estimate: datetime | None,
    events_rows: list[dict],
    analog_trace: AnalogTrace,
) -> dict:
    protocol_events = protocol.events if protocol is not None else []
    summary_row = {
        "trialID": trial_id,
        "stim_type": protocol.stim_mode if protocol is not None else "nostim",
        "number_of_stim": len(protocol_events),
        "initial_delay_sec": "",
        "avg_duration_sec": "",
        "avg_interval_sec": "",
        "strength": "",
        "pol_angle_list": "",
        "stim_protocol_id": protocol.run_id if protocol is not None else "",
        "stim_protocol_file": str(protocol.timestamp_log_path) if protocol is not None else "",
        "stim_protocol_dir": str(protocol.timestamp_log_path.parent) if protocol is not None else "",
        "trial_start_estimate": trial_start_estimate.isoformat() if trial_start_estimate is not None else "",
        "protocol_trial_start_estimate": (
            protocol.estimated_trial_start.isoformat()
            if protocol is not None and protocol.estimated_trial_start is not None
            else ""
        ),
        "protocol_match_delta_sec": round(float(protocol_match_delta_sec), 3)
        if protocol_match_delta_sec is not None
        else "",
        "analog_source": analog_trace.source,
        "raw_z_index": analog_trace.raw_z_index if analog_trace.raw_z_index is not None else "",
        "raw_z_strategy": analog_trace.raw_z_strategy,
    }

    if protocol is None or not protocol_events:
        return summary_row

    onsets = [_as_float_or_none(row.get("start_time_sec")) for row in events_rows]
    offsets = [_as_float_or_none(row.get("end_time_sec")) for row in events_rows]
    onsets = [onset for onset in onsets if onset is not None]
    offsets = [offset for offset in offsets if offset is not None]
    if onsets:
        summary_row["initial_delay_sec"] = round(float(onsets[0]), 2)
    if onsets and offsets and len(offsets) == len(onsets):
        durations = [offset - onset for onset, offset in zip(onsets, offsets)]
        summary_row["avg_duration_sec"] = round(float(np.mean(durations)), 2)
    if len(onsets) > 1:
        intervals = [onsets[i + 1] - onsets[i] for i in range(len(onsets) - 1)]
        summary_row["avg_interval_sec"] = round(float(np.mean(intervals)), 2)
    angles = [str(event.get("pol_angle", "")) for event in protocol_events if event.get("pol_angle", "") != ""]
    summary_row["pol_angle_list"] = ";".join(angles)

    return summary_row


def _format_ms_as_sec(value: object) -> str:
    if value is None or value == "":
        return ""
    try:
        return "{:.3g}s".format(float(value) / 1000.0)
    except (TypeError, ValueError):
        return ""


def compact_angle_summary(events: list[dict]) -> str:
    angles = [str(event.get("pol_angle", "")) for event in events if event.get("pol_angle", "") != ""]
    if not angles:
        return ""
    unique_angles = sorted(set(angles), key=angle_sort_key)
    if len(unique_angles) <= 8:
        return "angles: " + ", ".join([angle_label(angle) for angle in unique_angles])
    return "angles: {} unique".format(len(unique_angles))


def build_figure_notes(
    protocol: StimProtocol | None,
    protocol_match_delta_sec: float | None,
    analog_trace: AnalogTrace,
) -> list[str]:
    analog_label = analog_trace.source
    if analog_trace.raw_z_strategy:
        analog_label = "{} ({})".format(analog_label, analog_trace.raw_z_strategy)
    if analog_trace.raw_z_index is not None:
        analog_label = "{} z{}".format(analog_label, analog_trace.raw_z_index)

    if protocol is None:
        return [
            "protocol: none matched",
            "stim: nostim",
            "analog: {}".format(analog_label),
        ]

    mcu_config = protocol.config.get("mcu_config", {})
    mode = str(protocol.stim_mode or "").lower()
    lines = [
        "protocol: {}".format(protocol.run_id),
        "mode: {} | n={}".format(mode or "unknown", len(protocol.events)),
    ]
    if protocol_match_delta_sec is not None:
        lines.append("clock match: {:.1f}s".format(float(protocol_match_delta_sec)))

    initial_delay = _format_ms_as_sec(mcu_config.get("initial_delay_ms"))
    interval = _format_ms_as_sec(mcu_config.get("interval_ms"))
    if initial_delay or interval:
        lines.append("delay: {} | interval: {}".format(initial_delay or "NA", interval or "NA"))

    if mode == "pulse":
        lines.append(
            "pulse: {} x {} on / {} off".format(
                int(mcu_config.get("pulse_count", 0) or 0),
                _format_ms_as_sec(mcu_config.get("pulse_on_ms")) or "NA",
                _format_ms_as_sec(mcu_config.get("pulse_off_ms")) or "NA",
            )
        )
        if protocol.expected_duration_sec is not None:
            lines.append("packet: {:.3g}s".format(float(protocol.expected_duration_sec)))
    elif mode == "sustain":
        lines.append("stim on: {}".format(_format_ms_as_sec(mcu_config.get("stim_on_ms")) or "NA"))
    elif protocol.expected_duration_sec is not None:
        lines.append("duration: {:.3g}s".format(float(protocol.expected_duration_sec)))

    angle_summary = compact_angle_summary(protocol.events)
    if angle_summary:
        lines.append(angle_summary)
    lines.append("analog: {}".format(analog_label))
    return lines


def build_events_rows(
    trial_id: str,
    stim_blocks: list[dict],
    protocol: StimProtocol | None,
    protocol_match_delta_sec: float | None,
    trial_start_estimate: datetime | None,
) -> list[dict]:
    rows: list[dict] = []
    if protocol is not None:
        for idx, protocol_event in enumerate(protocol.events):
            onset_sec, offset_sec = protocol_event_time_in_trial(protocol_event, trial_start_estimate)
            analog_block = stim_blocks[idx] if idx < len(stim_blocks) else nearest_stim_block(stim_blocks, onset_sec)
            analog_start = analog_block.get("start_time_sec", "") if analog_block else ""
            analog_end = analog_block.get("end_time_sec", "") if analog_block else ""
            if analog_start != "":
                event_start = analog_start
                event_end = analog_end
                duration_sec = (
                    round(float(analog_end) - float(analog_start), 3)
                    if analog_end != ""
                    else protocol_event.get("duration_sec", "")
                )
                timing_source = "analog_voltage_with_protocol_metadata"
            else:
                if onset_sec is None:
                    continue
                event_start = onset_sec
                event_end = offset_sec if offset_sec is not None else ""
                duration_sec = (
                    round(float(offset_sec - onset_sec), 3)
                    if offset_sec is not None
                    else protocol_event.get("duration_sec", "")
                )
                timing_source = "protocol_absolute_time_fallback"
            analog_delta = (
                round(float(analog_start) - float(onset_sec), 3)
                if analog_start != "" and onset_sec is not None
                else ""
            )
            rows.append(
                {
                    "trialID": trial_id,
                    "stim_index": protocol_event.get("stim_index", len(rows) + 1),
                    "start_time_sec": event_start,
                    "end_time_sec": event_end,
                    "duration_sec": duration_sec,
                    "stim_type": protocol.stim_mode,
                    "pol_angle": protocol_event.get("pol_angle", ""),
                    "strength": "",
                    "stim_protocol_id": protocol.run_id,
                    "mcu_onset_sec": protocol_event.get("mcu_onset_sec", ""),
                    "mcu_offset_sec": protocol_event.get("mcu_offset_sec", ""),
                    "host_timestamp": protocol_event.get("host_timestamp", ""),
                    "timing_source": timing_source,
                    "protocol_match_delta_sec": round(float(protocol_match_delta_sec), 3)
                    if protocol_match_delta_sec is not None
                    else "",
                    "analog_detected_start_time_sec": analog_start,
                    "analog_detected_end_time_sec": analog_end,
                    "analog_minus_protocol_onset_sec": analog_delta,
                }
            )
        return rows

    return rows


def build_pulse_events_rows(
    trial_id: str,
    stim_blocks: list[dict],
    protocol: StimProtocol | None,
    trial_start_estimate: datetime | None,
) -> list[dict]:
    if protocol is None or protocol.stim_mode.lower() != "pulse":
        return []

    mcu_config = protocol.config.get("mcu_config", {})
    pulse_count = int(mcu_config.get("pulse_count", 0) or 0)
    pulse_on_sec = float(mcu_config.get("pulse_on_ms", 0) or 0) / 1000.0
    pulse_off_sec = float(mcu_config.get("pulse_off_ms", 0) or 0) / 1000.0
    if pulse_count <= 0 or pulse_on_sec <= 0:
        return []

    rows: list[dict] = []
    pulse_period_sec = pulse_on_sec + pulse_off_sec
    for stim_idx, protocol_event in enumerate(protocol.events):
        packet_onset_sec, _ = protocol_event_time_in_trial(protocol_event, trial_start_estimate)
        analog_block = nearest_stim_block(stim_blocks, packet_onset_sec)
        analog_packet_start = analog_block.get("start_time_sec", "") if analog_block else ""
        mcu_packet_start = protocol_event.get("mcu_onset_sec", "")
        angle = protocol_event.get("pol_angle", "")

        for pulse_index in range(1, pulse_count + 1):
            offset_sec = (pulse_index - 1) * pulse_period_sec
            mcu_onset = round(float(mcu_packet_start) + offset_sec, 6) if mcu_packet_start != "" else ""
            mcu_offset = round(float(mcu_packet_start) + offset_sec + pulse_on_sec, 6) if mcu_packet_start != "" else ""
            protocol_onset = round(float(packet_onset_sec) + offset_sec, 6) if packet_onset_sec is not None else ""
            protocol_offset = (
                round(float(packet_onset_sec) + offset_sec + pulse_on_sec, 6)
                if packet_onset_sec is not None
                else ""
            )
            analog_onset = round(float(analog_packet_start) + offset_sec, 6) if analog_packet_start != "" else ""
            analog_offset = round(float(analog_packet_start) + offset_sec + pulse_on_sec, 6) if analog_packet_start != "" else ""
            pulse_block_index = stim_idx * pulse_count + pulse_index - 1
            pulse_block = stim_blocks[pulse_block_index] if pulse_block_index < len(stim_blocks) else None
            if pulse_block is not None:
                analog_onset = pulse_block.get("start_time_sec", analog_onset)
                analog_offset = pulse_block.get("end_time_sec", analog_offset)
                timing_source = "analog_voltage_flash_with_protocol_metadata"
            else:
                timing_source = (
                    "protocol_absolute_time_plus_analog_packet"
                    if analog_packet_start != ""
                    else "protocol_absolute_time"
                )

            rows.append(
                {
                    "trialID": trial_id,
                    "stim_index": protocol_event.get("stim_index", ""),
                    "pulse_index": pulse_index,
                    "stim_type": "pulse",
                    "pol_angle": angle,
                    "stim_protocol_id": protocol.run_id,
                    "mcu_packet_onset_sec": mcu_packet_start,
                    "protocol_packet_onset_sec": packet_onset_sec if packet_onset_sec is not None else "",
                    "analog_packet_onset_sec": analog_packet_start,
                    "pulse_on_sec": round(pulse_on_sec, 6),
                    "pulse_off_sec": round(pulse_off_sec, 6),
                    "mcu_pulse_onset_sec": mcu_onset,
                    "mcu_pulse_offset_sec": mcu_offset,
                    "protocol_pulse_onset_sec": protocol_onset,
                    "protocol_pulse_offset_sec": protocol_offset,
                    "analog_anchored_pulse_onset_sec": analog_onset if analog_onset != "" else protocol_onset,
                    "analog_anchored_pulse_offset_sec": analog_offset if analog_offset != "" else protocol_offset,
                    "timing_source": timing_source,
                }
            )
    return rows


def block_judgement_rows(
    stim_blocks: list[dict],
    events_rows: list[dict],
    tolerance_sec: float = 0.35,
) -> list[dict]:
    rows: list[dict] = []
    for block_index, block in enumerate(stim_blocks, start=1):
        start = _as_float_or_none(block.get("start_time_sec"))
        end = _as_float_or_none(block.get("end_time_sec"))
        duration = _as_float_or_none(block.get("duration_sec"))
        matched_event = None
        for event in events_rows:
            analog_start = _as_float_or_none(event.get("analog_detected_start_time_sec"))
            analog_end = _as_float_or_none(event.get("analog_detected_end_time_sec"))
            event_start = _as_float_or_none(event.get("start_time_sec"))
            if start is None:
                continue
            if analog_start is not None and abs(analog_start - start) <= tolerance_sec:
                matched_event = event
                break
            if analog_end is not None and end is not None and abs(analog_end - end) <= tolerance_sec:
                matched_event = event
                break
            if event_start is not None and abs(event_start - start) <= tolerance_sec:
                matched_event = event
                break
        rows.append(
            {
                "block_index": block_index,
                "stim_index_detected": block.get("stim_index", block_index),
                "start_time_sec": block.get("start_time_sec", ""),
                "end_time_sec": block.get("end_time_sec", ""),
                "duration_sec": block.get("duration_sec", duration if duration is not None else ""),
                "final_is_stim_event": 1 if matched_event is not None else 0,
                "matched_final_stim_index": matched_event.get("stim_index", "") if matched_event is not None else "",
                "matched_timing_source": matched_event.get("timing_source", "") if matched_event is not None else "",
                "matched_stim_type": matched_event.get("stim_type", "") if matched_event is not None else "",
                "matched_pol_angle": matched_event.get("pol_angle", "") if matched_event is not None else "",
            }
        )
    return rows


def trial_date_label(trial_id: str, summary_row: dict | None = None) -> str:
    if summary_row is not None:
        trial_start_estimate = str(summary_row.get("trial_start_estimate", "") or "").strip()
        if trial_start_estimate:
            return trial_start_estimate[:10].replace("-", "")
    match = re.match(r"^(\d{8})", trial_id)
    if match:
        return match.group(1)
    return ""


def build_block_summary_rows(
    summaries: list[dict],
    block_rows_by_trial: dict[str, list[dict]],
) -> list[dict]:
    summary_by_trial = {str(row.get("trialID", "")): row for row in summaries}
    rows: list[dict] = []
    for trial_id in sorted(block_rows_by_trial):
        block_rows = block_rows_by_trial[trial_id]
        summary_row = summary_by_trial.get(trial_id, {})
        n_blocks_total = len(block_rows)
        n_final_one = sum(int(row.get("final_is_stim_event", 0) or 0) for row in block_rows)
        rows.append(
            {
                "date": trial_date_label(trial_id, summary_row),
                "trialID": trial_id,
                "n_blocks_total": n_blocks_total,
                "n_final_is_1": n_final_one,
                "n_final_is_0": n_blocks_total - n_final_one,
                "stim_type": summary_row.get("stim_type", ""),
                "number_of_stim": summary_row.get("number_of_stim", ""),
                "stim_protocol_id": summary_row.get("stim_protocol_id", ""),
                "protocol_match_delta_sec": summary_row.get("protocol_match_delta_sec", ""),
            }
        )
    return rows


def plot_stim_event_slice_panels(
    brightness_trace: np.ndarray,
    time_axis: np.ndarray,
    stim_blocks: list[dict],
    block_rows: list[dict],
    dynamic_thresh: float | None,
    trial_id: str,
    output_dir: Path,
    figure_notes: list[str] | None = None,
) -> None:
    if not stim_blocks or not block_rows or len(time_axis) == 0:
        return

    output_dir.mkdir(parents=True, exist_ok=True)
    global_y_min = float(np.nanmin(brightness_trace)) if len(brightness_trace) else 0.0
    global_y_max = float(np.nanmax(brightness_trace)) if len(brightness_trace) else 1.0
    y_pad = max((global_y_max - global_y_min) * 0.08, 1.0)

    block_by_index = {int(row.get("block_index", idx + 1)): row for idx, row in enumerate(block_rows)}
    note_lines = [str(line) for line in (figure_notes or []) if str(line).strip()]
    for panel_index, block in enumerate(stim_blocks):
        block_index = int(block.get("stim_index", panel_index + 1))
        start = _as_float_or_none(block.get("start_time_sec"))
        end = _as_float_or_none(block.get("end_time_sec"))
        if start is None or end is None:
            continue
        duration = max(0.1, end - start)
        pad = max(1.0, duration * 1.5)
        left = max(0.0, start - pad)
        right = min(float(time_axis[-1]), end + pad)
        mask = (time_axis >= left) & (time_axis <= right)
        local_time = time_axis[mask]
        local_trace = brightness_trace[mask]
        if len(local_time) == 0:
            continue
        fig, ax = plt.subplots(1, 1, figsize=(6.4, 3.8))
        ax.plot(local_time, local_trace, color="#2563eb", linewidth=0.9, alpha=0.85)
        if dynamic_thresh is not None:
            ax.axhline(dynamic_thresh, color="#dc2626", linestyle="--", linewidth=0.8)
        judged = block_by_index.get(block_index, {})
        flag = int(judged.get("final_is_stim_event", 0) or 0)
        color = "#16a34a" if flag == 1 else "#dc2626"
        ax.axvspan(start, end, color=color, alpha=0.22)
        ax.text(
            0.02,
            0.96,
            f"#{block_index}  {flag}",
            transform=ax.transAxes,
            ha="left",
            va="top",
            fontsize=9,
            fontweight="bold",
            color=color,
            bbox={
                "boxstyle": "round,pad=0.18",
                "facecolor": "white",
                "edgecolor": color,
                "alpha": 0.88,
                "linewidth": 0.7,
            },
        )
        if judged.get("matched_final_stim_index", "") != "":
            ax.text(
                0.98,
                0.96,
                f"final #{judged.get('matched_final_stim_index')}",
                transform=ax.transAxes,
                ha="right",
                va="top",
                fontsize=8,
                color="#374151",
            )
        ax.set_xlim(left, right)
        ax.set_ylim(global_y_min - y_pad, global_y_max + y_pad)
        ax.set_xlabel("sec", fontsize=9)
        ax.set_ylabel("a.u.", fontsize=9)
        ax.set_title(
            f"Stimulus block #{block_index} ({flag}) - {trial_id}",
            fontsize=11,
            fontweight="bold",
        )
        ax.grid(True, alpha=0.22)
        if note_lines:
            fig.text(0.01, 0.01, "\n".join(note_lines), ha="left", va="bottom", fontsize=8)
        panel_path = output_dir / f"{trial_id}_stim_block_{block_index:03d}.png"
        try:
            fig.tight_layout(rect=(0.0, 0.05, 1.0, 0.96))
            save_figure_with_pdf(fig, panel_path, dpi=150)
        finally:
            plt.close(fig)


