def is_nostim(b_max: float, b_min: float, rel_thresh: float) -> bool:
    if b_max <= 0:
        return True
    return ((b_max - b_min) / b_max) < rel_thresh


def process_trial(
    trial: TrialInput,
    out_dir: Path,
    action: str,
    dry_run: bool,
    nostim_rel_thresh: float,
    protocols: list[StimProtocol],
    analog_source: str,
    raw_z_strategy: str,
) -> tuple[dict | None, list[dict], list[dict], str]:
    if required_outputs_done(out_dir, trial.trial_id) and action == "skip":
        return None, [], [], "skipped"

    if dry_run:
        LOGGER.info("[dry-run] 将处理 %s -> %s", trial.input_dir, out_dir)
        return None, [], [], "processed"

    if action == "overwrite":
        clean_step_outputs(out_dir, trial.trial_id)

    with trial.metadata_path.open("r", encoding="utf-8") as handle:
        meta = json.load(handle)
    dt = float(meta.get("temporal_calibration", {}).get("frame_interval_sec", 1.0) or 1.0)
    n_z = int(meta.get("dimensions", {}).get("z_slices", 1) or 1)
    timepoints = int(meta.get("dimensions", {}).get("timepoints", 0) or 0)
    if dt <= 0:
        LOGGER.warning("%s 的 frame_interval_sec=%s；将使用 1.0 秒。", trial.trial_id, dt)
        dt = 1.0

    analog_trace = read_analog_trace(trial, analog_source, raw_z_strategy)
    brightness_trace = analog_trace.trace
    analog_dt = dt * analog_trace.dt_scale
    time_axis = np.arange(len(brightness_trace)) * analog_dt

    b_max = float(np.max(brightness_trace))
    b_min = float(np.min(brightness_trace))
    if is_nostim(b_max, b_min, nostim_rel_thresh):
        stim_blocks: list[dict] = []
        dynamic_thresh = None
    else:
        dynamic_thresh = b_min + 1 / (n_z + 1) * (b_max - b_min)
        stim_blocks = analyze_stim_blocks(
            brightness_trace=brightness_trace,
            dt=analog_dt,
            dynamic_thresh=dynamic_thresh,
            baseline=b_min,
            peak=b_max,
        )

    trial_start_estimate = estimate_trial_start_from_metadata(meta, trial.raw_oir_path, timepoints, dt)
    protocol, protocol_match_delta_sec = match_stim_protocol(protocols, trial_start_estimate)
    if protocol is not None:
        LOGGER.info(
            "Matched %s to stimulus protocol %s (%s, absolute start delta %.3fs).",
            trial.trial_id,
            protocol.run_id,
            protocol.stim_mode or "unknown mode",
            protocol_match_delta_sec if protocol_match_delta_sec is not None else float("nan"),
        )
    else:
        LOGGER.info("%s 未按绝对时间匹配到刺激协议；标记为 nostim。", trial.trial_id)

    packet_stim_blocks = packet_blocks_from_pulse_blocks(stim_blocks, protocol)
    events_rows = build_events_rows(
        trial.trial_id,
        packet_stim_blocks,
        protocol,
        protocol_match_delta_sec,
        trial_start_estimate,
    )
    summary_row = build_summary_row(
        trial.trial_id,
        protocol,
        protocol_match_delta_sec,
        trial_start_estimate,
        events_rows,
        analog_trace,
    )
    pulse_events_rows = build_pulse_events_rows(trial.trial_id, stim_blocks, protocol, trial_start_estimate)
    block_rows = block_judgement_rows(stim_blocks, events_rows)
    figure_notes = build_figure_notes(protocol, protocol_match_delta_sec, analog_trace)
    display_stim_blocks = [
        {
            "stim_index": row.get("stim_index", index + 1),
            "start_time_sec": row.get("start_time_sec"),
            "end_time_sec": row.get("end_time_sec"),
            "duration_sec": row.get("duration_sec", ""),
            "pol_angle": row.get("pol_angle", ""),
        }
        for index, row in enumerate(events_rows)
    ]
    save_trial_outputs(
        out_dir=out_dir,
        trial_id=trial.trial_id,
        brightness_trace=brightness_trace,
        time_axis=time_axis,
        summary_row=summary_row,
        events_rows=events_rows,
        pulse_events_rows=pulse_events_rows,
        display_stim_blocks=display_stim_blocks,
        diagnostic_stim_blocks=stim_blocks,
        block_rows=block_rows,
        dynamic_thresh=dynamic_thresh,
        analog_trace=analog_trace,
        figure_notes=figure_notes,
    )
    return summary_row, events_rows, pulse_events_rows, "processed"


