def expected_duration_from_config(config: dict) -> float | None:
    if not config:
        return None
    if config.get("computed_stim_total_ms") is not None:
        return float(config["computed_stim_total_ms"]) / 1000.0

    mcu_config = config.get("mcu_config", {})
    stim_mode = str(mcu_config.get("stim_mode", "")).lower()
    if stim_mode == "sustain" and mcu_config.get("stim_on_ms") is not None:
        return float(mcu_config["stim_on_ms"]) / 1000.0
    if stim_mode == "pulse":
        pulse_count = int(mcu_config.get("pulse_count", 0) or 0)
        pulse_on_ms = float(mcu_config.get("pulse_on_ms", 0) or 0)
        pulse_off_ms = float(mcu_config.get("pulse_off_ms", 0) or 0)
        if pulse_count > 0:
            total_ms = pulse_count * pulse_on_ms + max(0, pulse_count - 1) * pulse_off_ms
            return total_ms / 1000.0
    return None


def read_protocol_events(timestamp_log_path: Path, stim_map_path: Path | None, expected_duration_sec: float | None) -> list[dict]:
    timestamp_df = pd.read_csv(timestamp_log_path)
    angle_by_index: dict[int, object] = {}
    if stim_map_path is not None and stim_map_path.exists():
        stim_map_df = pd.read_csv(stim_map_path)
        if {"stim_id", "angle"}.issubset(stim_map_df.columns):
            angle_by_index = {
                int(row["stim_id"]): row["angle"]
                for _, row in stim_map_df.iterrows()
                if pd.notna(row.get("stim_id"))
            }

    events: list[dict] = []
    for _, row in timestamp_df.iterrows():
        event_name = str(row.get("event", ""))
        if not event_name.startswith("STIM_"):
            continue

        stim_index_raw = row.get("mcu_stim_index")
        if pd.isna(stim_index_raw):
            match = re.search(r"(\d+)$", event_name)
            stim_index = int(match.group(1)) if match else len(events) + 1
        else:
            stim_index = int(stim_index_raw)

        mcu_offset_ms = row.get("mcu_offset_ms")
        mcu_onset_sec = float(mcu_offset_ms) / 1000.0 if pd.notna(mcu_offset_ms) else np.nan
        angle = row.get("angle")
        if pd.isna(angle):
            angle = angle_by_index.get(stim_index, "")

        event = {
            "stim_index": stim_index,
            "mcu_onset_sec": round(float(mcu_onset_sec), 3) if pd.notna(mcu_onset_sec) else "",
            "mcu_offset_sec": round(float(mcu_onset_sec + expected_duration_sec), 3)
            if pd.notna(mcu_onset_sec) and expected_duration_sec is not None
            else "",
            "duration_sec": round(float(expected_duration_sec), 3)
            if expected_duration_sec is not None
            else "",
            "pol_angle": angle if pd.notna(angle) else "",
            "host_timestamp": row.get("host_timestamp", ""),
        }
        events.append(event)

    return events


def parse_host_datetime(value: object) -> datetime | None:
    if value is None or pd.isna(value):
        return None
    text = str(value).strip()
    if not text:
        return None
    try:
        return datetime.fromisoformat(text)
    except ValueError:
        return None


def estimate_protocol_trial_start(events: list[dict]) -> datetime | None:
    for event in events:
        host_time = parse_host_datetime(event.get("host_timestamp"))
        mcu_onset_sec = event.get("mcu_onset_sec")
        if host_time is None or mcu_onset_sec == "":
            continue
        return host_time - timedelta(seconds=float(mcu_onset_sec))
    return None


def discover_stim_protocols(stim_log_root: Path | None) -> list[StimProtocol]:
    if stim_log_root is None:
        return []
    if not stim_log_root.exists():
        LOGGER.warning("刺激日志根目录不存在：%s", stim_log_root)
        return []

    protocols: list[StimProtocol] = []
    for timestamp_log_path in sorted(stim_log_root.rglob("timestamp_log_*.csv")):
        run_id = parse_run_id(timestamp_log_path, "timestamp_log_", ".csv")
        if not run_id:
            continue

        log_dir = timestamp_log_path.parent
        config_path = log_dir / f"experiment_config_{run_id}.json"
        stim_map_path = log_dir / f"stim_map_{run_id}.csv"
        config = read_json_if_exists(config_path if config_path.exists() else None)
        mcu_config = config.get("mcu_config", {})
        stim_mode = str(mcu_config.get("stim_mode", "") or "")
        expected_duration_sec = expected_duration_from_config(config)
        events = read_protocol_events(
            timestamp_log_path=timestamp_log_path,
            stim_map_path=stim_map_path if stim_map_path.exists() else None,
            expected_duration_sec=expected_duration_sec,
        )
        estimated_trial_start = estimate_protocol_trial_start(events)
        protocols.append(
            StimProtocol(
                run_id=run_id,
                timestamp_log_path=timestamp_log_path,
                stim_map_path=stim_map_path if stim_map_path.exists() else None,
                config_path=config_path if config_path.exists() else None,
                config=config,
                stim_mode=stim_mode,
                expected_duration_sec=expected_duration_sec,
                estimated_trial_start=estimated_trial_start,
                events=events,
            )
        )

    LOGGER.info("找到 %d 个刺激协议日志。", len(protocols))
    return protocols


def nearest_stim_block(
    stim_blocks: list[dict],
    target_onset_sec: float | None,
    max_delta_sec: float = 3.0,
) -> dict | None:
    if target_onset_sec is None or not stim_blocks:
        return None

    best_block = min(
        stim_blocks,
        key=lambda block: abs(float(block["start_time_sec"]) - target_onset_sec),
    )
    delta = abs(float(best_block["start_time_sec"]) - target_onset_sec)
    return best_block if delta <= max_delta_sec else None


def pulse_count_from_protocol(protocol: StimProtocol | None) -> int:
    if protocol is None or protocol.stim_mode.lower() != "pulse":
        return 0
    mcu_config = protocol.config.get("mcu_config", {})
    return int(mcu_config.get("pulse_count", 0) or 0)


def packet_blocks_from_pulse_blocks(stim_blocks: list[dict], protocol: StimProtocol | None) -> list[dict]:
    pulse_count = pulse_count_from_protocol(protocol)
    if protocol is None or pulse_count <= 1:
        return stim_blocks
    expected_pulses = len(protocol.events) * pulse_count
    if len(stim_blocks) < expected_pulses:
        return stim_blocks

    packet_blocks: list[dict] = []
    for stim_idx, protocol_event in enumerate(protocol.events):
        first = stim_idx * pulse_count
        packet = stim_blocks[first : first + pulse_count]
        if len(packet) != pulse_count:
            continue
        start_time = float(packet[0].get("start_time_sec", 0))
        end_time = float(packet[-1].get("end_time_sec", start_time))
        packet_blocks.append(
            {
                "stim_index": protocol_event.get("stim_index", stim_idx + 1),
                "start_frame": packet[0].get("start_frame", ""),
                "end_frame": packet[-1].get("end_frame", ""),
                "start_time_sec": round(start_time, 3),
                "end_time_sec": round(end_time, 3),
                "duration_sec": round(end_time - start_time, 3),
                "pol_angle": protocol_event.get("pol_angle", ""),
            }
        )
    return packet_blocks if packet_blocks else stim_blocks


def protocol_event_time_in_trial(
    event: dict,
    trial_start_estimate: datetime | None,
) -> tuple[float | None, float | None]:
    if trial_start_estimate is None:
        return None, None

    host_time = parse_host_datetime(event.get("host_timestamp"))
    if host_time is None:
        return None, None

    onset_sec = (host_time - trial_start_estimate).total_seconds()
    duration = _as_float_or_none(event.get("duration_sec"))
    if duration is None:
        mcu_onset = _as_float_or_none(event.get("mcu_onset_sec"))
        mcu_offset = _as_float_or_none(event.get("mcu_offset_sec"))
        if mcu_onset is not None and mcu_offset is not None:
            duration = mcu_offset - mcu_onset
    if duration is None or duration <= 0:
        return round(float(onset_sec), 3), None
    return round(float(onset_sec), 3), round(float(onset_sec + duration), 3)


def match_stim_protocol(
    protocols: list[StimProtocol],
    trial_start_estimate: datetime | None,
) -> tuple[StimProtocol | None, float | None]:
    if trial_start_estimate is None or not protocols:
        return None, None

    best_protocol: StimProtocol | None = None
    best_delta_sec: float | None = None

    for protocol in protocols:
        if protocol.estimated_trial_start is None:
            continue
        delta_sec = abs((trial_start_estimate - protocol.estimated_trial_start).total_seconds())
        if best_delta_sec is None or delta_sec < best_delta_sec:
            best_delta_sec = delta_sec
            best_protocol = protocol

    if best_delta_sec is None or best_delta_sec > DEFAULT_PROTOCOL_MATCH_TOLERANCE_SEC:
        return None, None
    return best_protocol, best_delta_sec


