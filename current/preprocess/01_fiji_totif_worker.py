# Purpose
# -------
# Convert Olympus .oir recordings into TIF files readable by the
# downstream calcium-imaging pipeline.
#
# Output layout
# -------------
# For input:
#   DATA_ROOT/<trial>/<trial>.oir
# or:
#   DATA_ROOT/<date_folder>/<trial>/<trial>.oir
