# Output:
#   OUTPUT_ROOT/01_oir_to_tif/<trial>/
# or:
#   OUTPUT_ROOT/01_oir_to_tif/<date_folder>/<trial>/
#       <title>_metadata.json
#       <title>_Max_Proj.tif
#       <title>_Stim_Analog.tif   # if channel 2 exists
#       <title>_Stim_Analog_Raw/      # optional unprojected plane series
#
# Existing-output behavior
# ------------------------
# existingMode = "skip"
#     Skip before opening .oir if required outputs already exist.
# existingMode = "overwrite"
#     Delete old step-01 outputs in the target folder, then rerun.
# existingMode = "keep"
#     Rerun without deleting old outputs.
#
# The skip check is intentionally placed BEFORE BF.openImagePlus(), because
# opening .oir in Bio-Formats Full RAM mode is the slow step.
# ============================================================


# -------------------- Configuration --------------------
VALID_EXISTING_MODES = set(["skip", "overwrite", "keep"])
VALID_PROJECTION_MODES = set(["auto", "safe", "fast"])
VALID_METADATA_MODES = set(["skip", "update-missing", "refresh"])
VALID_STIM_EXPORT_MODES = set(["projected", "raw", "both"])
AUTO_FAST_MAX_TIMEPOINTS = 600
AUTO_FAST_MAX_Z_SLICES = 5

# If True, strict skip requires Stim_Analog.tif for already-known two-channel
# outputs. Because we cannot know nC without opening the .oir, the default
# skip criterion is metadata + Max_Proj only. This is safer for mixed 1-channel
# and 2-channel datasets.
STRICT_REQUIRE_STIM_FOR_SKIP = False

# Files generated by this step and safe to remove in overwrite mode.
STEP01_OUTPUT_PATTERNS = [
    "*_metadata.json",
    "*_Max_Proj.tif",
    "*_Max_Proj.tiff",
    "*_Stim_Analog.tif",
    "*_Stim_Analog.tiff",
    "*_Stim_Analog_Raw.tif",
    "*_Stim_Analog_Raw.tiff",
    "*_Stim_Analog_Raw",
]
