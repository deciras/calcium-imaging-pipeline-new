def clean_step_outputs(out_dir: Path) -> int:
    if not out_dir.exists():
        return 0
    removed = 0
    for pattern in STEP_OUTPUT_PATTERNS:
        for path in out_dir.glob(pattern):
            if path.is_dir():
                shutil.rmtree(path)
                removed += 1
                LOGGER.info("Removed old step-06 folder: %s", path)
            elif path.is_file() or path.is_symlink():
                path.unlink()
                removed += 1
                LOGGER.info("Removed old step-06 file: %s", path)
    return removed


def make_temp_output_dir(out_dir: Path) -> Path:
    out_dir.parent.mkdir(parents=True, exist_ok=True)
    return Path(tempfile.mkdtemp(prefix=f".{out_dir.name}.tmp-", dir=out_dir.parent))


def remove_path(path: Path) -> None:
    if path.is_dir():
        shutil.rmtree(path)
    elif path.exists() or path.is_symlink():
        path.unlink()


def install_temp_outputs(temp_dir: Path, out_dir: Path, clean_existing: bool) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    if clean_existing:
        clean_step_outputs(out_dir)
    for src in temp_dir.iterdir():
        dst = out_dir / src.name
        if dst.exists() or dst.is_symlink():
            remove_path(dst)
        shutil.move(str(src), str(dst))
    shutil.rmtree(temp_dir, ignore_errors=True)


def copy_if_exists(src: Path | None, dst: Path) -> bool:
    if src is None or not src.exists():
        return False
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)
    LOGGER.info("Copied %s -> %s", src, dst)
    return True


