def load_ops(path: Path) -> dict:
    if not path.exists():
        return {}
    try:
        value = np.load(path, allow_pickle=True)
        item = value.item()
        return item if isinstance(item, dict) else {}
    except Exception:
        return {}


def validate_suite2p_arrays(trial: TrialInput) -> None:
    missing = [
        path.name
        for path in (trial.f_path, trial.fneu_path, trial.iscell_path, trial.stat_path, trial.ops_path)
        if not path.exists()
    ]
    if missing:
        raise FileNotFoundError(f"Missing required suite2p input(s): {', '.join(missing)}")


def load_suite2p_inputs(trial: TrialInput) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, dict]:
    validate_suite2p_arrays(trial)
    f_raw = np.load(trial.f_path, allow_pickle=True).astype(np.float32, copy=False)
    fneu = np.load(trial.fneu_path, allow_pickle=True).astype(np.float32, copy=False)
    iscell = np.load(trial.iscell_path, allow_pickle=True)
    stat = np.load(trial.stat_path, allow_pickle=True)
    ops = load_ops(trial.ops_path)

    if f_raw.ndim != 2 or fneu.ndim != 2:
        raise ValueError(f"F/Fneu must be 2D ROI x frame arrays, got F={f_raw.shape}, Fneu={fneu.shape}")
    if f_raw.shape != fneu.shape:
        raise ValueError(f"F and Fneu shape mismatch: {f_raw.shape} vs {fneu.shape}")
    if iscell.ndim != 2 or iscell.shape[0] != f_raw.shape[0]:
        raise ValueError(f"iscell.npy shape invalid: {iscell.shape}, expected rows={f_raw.shape[0]}")
    if len(stat) != f_raw.shape[0]:
        raise ValueError(f"stat.npy length mismatch: {len(stat)} vs n_roi={f_raw.shape[0]}")
    return f_raw, fneu, iscell, stat, ops


def manual_plane0_dir(manual_root: Path, trial: TrialInput) -> Path:
    return manual_root / trial.rel_parent / trial.trial_id / "suite2p_compatible" / "plane0"


def load_manual_roi_inputs(
    manual_root: Path,
    trial: TrialInput,
) -> tuple[np.ndarray, np.ndarray, np.ndarray | None, np.ndarray | None, str] | None:
    plane0 = manual_plane0_dir(manual_root, trial)
    stat_path = plane0 / "stat.npy"
    if not stat_path.exists():
        return None

    stat = np.load(stat_path, allow_pickle=True)
    if len(stat) == 0:
        raise ValueError(f"Manual ROI stat.npy contains no ROI: {stat_path}")

    iscell_path = plane0 / "iscell.npy"
    if iscell_path.exists():
        iscell = np.load(iscell_path, allow_pickle=True)
    else:
        iscell = np.ones((len(stat), 2), dtype=np.float32)
    if iscell.ndim != 2 or iscell.shape[0] != len(stat):
        raise ValueError(f"Manual iscell shape invalid: {iscell.shape}, expected rows={len(stat)}")

    f_path = plane0 / "F.npy"
    fneu_path = plane0 / "Fneu.npy"
    f_raw = np.load(f_path, allow_pickle=True).astype(np.float32, copy=False) if f_path.exists() else None
    fneu = np.load(fneu_path, allow_pickle=True).astype(np.float32, copy=False) if fneu_path.exists() else None
    return stat, iscell, f_raw, fneu, str(plane0)


def select_rois(
    iscell: np.ndarray,
    include_noncell: bool,
    roi_source: str,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, str, str | None]:
    iscell_flag = iscell[:, 0].astype(bool)
    iscell_prob = iscell[:, 1].astype(float) if iscell.shape[1] >= 2 else np.full(iscell.shape[0], np.nan)
    selection_label = "iscell"
    selection_path = None

    if roi_source == "all" or include_noncell:
        selected = np.arange(iscell.shape[0], dtype=int)
        return selected, iscell_flag, iscell_prob, "all_suite2p_roi", selection_path

    selected = np.where(iscell_flag)[0].astype(int)
    return selected, iscell_flag, iscell_prob, selection_label, selection_path


