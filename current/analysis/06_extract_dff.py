def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    configure_logging(args.verbose)
    if args.plot_dpi is None:
        args.plot_dpi = args.dpi

    data_root = args.data_root.expanduser().resolve()
    output_root = args.output_root.expanduser().resolve() if args.output_root else default_output_root(data_root).resolve()
    input_root = args.input_root.expanduser().resolve() if args.input_root else default_input_root(output_root).resolve()
    args.manual_root = args.manual_root.expanduser().resolve() if args.manual_root else default_manual_root(output_root).resolve()
    stim_root = default_stim_root(output_root).resolve()
    out_root = step_output_root(output_root)

    if not input_root.exists():
        if args.dry_run:
            LOGGER.warning("Input root does not exist yet: %s", input_root)
            return 0
        LOGGER.error("Input root does not exist: %s", input_root)
        return 1

    trials = discover_trials(input_root, stim_root)
    if args.trial_id:
        wanted = {item.strip() for item in args.trial_id.split(",") if item.strip()}
        trials = [trial for trial in trials if trial.trial_id in wanted]
    summary = RunSummary(found=len(trials))
    rows: list[dict] = []

    LOGGER.info("Input root : %s", input_root)
    LOGGER.info("Manual root: %s", args.manual_root)
    LOGGER.info("Stim root  : %s", stim_root)
    LOGGER.info("Output root: %s", out_root)
    LOGGER.info("Found %d trial(s) with suite2p F.npy.", len(trials))

    for trial in trials:
        out_dir = trial_output_dir(out_root, trial)
        if required_outputs_done(out_dir, trial.trial_id) and args.action == "skip":
            if args.refresh_plots:
                if args.dry_run:
                    summary.processed += 1
                    LOGGER.info("[dry-run] Would refresh step-06 QC plots for %s -> %s", trial.trial_id, out_dir)
                elif refresh_trial_plots(out_dir, trial.trial_id, args):
                    summary.processed += 1
                    LOGGER.info("[plots] refreshed step-06 QC plots for %s", trial.trial_id)
                else:
                    summary.skipped += 1
                continue
            summary.skipped += 1
            LOGGER.info("[skip] %s", trial.trial_id)
            continue

        if args.dry_run:
            summary.processed += 1
            LOGGER.info("[dry-run] Would extract dF/F from %s -> %s", trial.plane0_dir, out_dir)
            continue

        temp_dir = make_temp_output_dir(out_dir)
        try:
            status, row = process_trial(trial, temp_dir, args)
            if status == "processed":
                install_temp_outputs(temp_dir, out_dir, clean_existing=args.action == "overwrite")
            else:
                shutil.rmtree(temp_dir, ignore_errors=True)
            rows.append(row)
            if status == "processed":
                summary.processed += 1
                LOGGER.info("[ok] %s: n_roi=%s n_frames=%s", trial.trial_id, row.get("n_roi_selected"), row.get("n_frames"))
            elif status == "skipped":
                summary.skipped += 1
                LOGGER.info("[skip] %s: %s", trial.trial_id, row.get("message"))
            else:
                summary.failed += 1
                LOGGER.error("[failed] %s: %s", trial.trial_id, row.get("message"))
        except Exception as exc:
            shutil.rmtree(temp_dir, ignore_errors=True)
            summary.failed += 1
            LOGGER.exception("[failed] %s: %s", trial.trial_id, exc)
            rows.append({"trial_id": trial.trial_id, "status": "failed", "message": str(exc)})

    if rows:
        out_root.mkdir(parents=True, exist_ok=True)
        pd.DataFrame(rows).to_csv(out_root / "dff_summary.csv", index=False)

    LOGGER.info("Summary:")
    LOGGER.info("  found: %d", summary.found)
    LOGGER.info("  processed or would process: %d", summary.processed)
    LOGGER.info("  skipped: %d", summary.skipped)
    LOGGER.info("  failed: %d", summary.failed)
    return 1 if summary.failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
