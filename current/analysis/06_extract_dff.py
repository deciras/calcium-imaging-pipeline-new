def find_first_existing(folder: Path, patterns: tuple[str, ...]) -> Path | None:
    for pattern in patterns:
        matches = sorted(folder.glob(pattern))
        if matches:
            return matches[0]
    return None


def find_stim_sidecar(folder: Path, trial_id: str, patterns: tuple[str, ...]) -> Path | None:
    preferred = tuple(f"{trial_id}{pattern[1:]}" if pattern.startswith("*") else pattern for pattern in patterns)
    found = find_first_existing(folder, preferred)
    if found is not None:
        return found
    return find_first_existing(folder, patterns)


def resolve_stim_sidecar(preferred_dir: Path, fallback_dir: Path, trial_id: str, patterns: tuple[str, ...]) -> Path | None:
    if preferred_dir.exists():
        found = find_stim_sidecar(preferred_dir, trial_id, patterns)
        if found is not None:
            return found
    return find_stim_sidecar(fallback_dir, trial_id, patterns)


def discover_trials(input_root: Path, stim_root: Path) -> list[TrialInput]:
    trials: list[TrialInput] = []
    for f_path in sorted(input_root.rglob("suite2p/plane0/F.npy")):
        plane0_dir = f_path.parent
        input_dir = plane0_dir.parent.parent
        trial_id = input_dir.name
        rel_parent = input_dir.parent.relative_to(input_root)
        stim_dir = stim_root / rel_parent / trial_id
        trials.append(
            TrialInput(
                trial_id=trial_id,
                rel_parent=rel_parent,
                input_dir=input_dir,
                plane0_dir=plane0_dir,
                f_path=f_path,
                fneu_path=plane0_dir / "Fneu.npy",
                iscell_path=plane0_dir / "iscell.npy",
                stat_path=plane0_dir / "stat.npy",
                ops_path=plane0_dir / "ops.npy",
                metadata_path=find_first_existing(input_dir, ("*_metadata.json",)),
                stim_events_path=resolve_stim_sidecar(stim_dir, input_dir, trial_id, ("*_stim_events.csv",)),
                stim_map_path=resolve_stim_sidecar(stim_dir, input_dir, trial_id, ("*_stim_map.csv",)),
                stim_pulse_events_path=resolve_stim_sidecar(stim_dir, input_dir, trial_id, ("*_stim_pulse_events.csv",)),
            )
        )
    return trials


