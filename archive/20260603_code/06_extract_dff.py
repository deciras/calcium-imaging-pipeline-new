"""
Extract neuropil-corrected dF/F traces from suite2p outputs.

Default layout:
  input : DATA_ROOT/05_suite2p_roi_detection/
  output: DATA_ROOT/06_dff/

By default, this step uses suite2p only for ROI position/shape and extracts
fluorescence again from the motion-corrected movie. This keeps suite2p detection
free to use a spatial high-pass image while downstream traces still come from
the biologically meaningful corrected movie. Existing outputs are skipped by
default, and overwrite only removes files generated by this step.

By default, ROI selection uses the manual curation output when it exists, then
falls back to suite2p iscell.npy. Manual curation provides ROI position/shape;
traces are still extracted from the motion-corrected movie.
"""

