def movie_as_tyx(path: Path) -> np.ndarray:
    try:
        movie = tf.memmap(path)
    except Exception:
        movie = tf.imread(path)
    arr = np.asarray(movie)
    if arr.ndim == 2:
        arr = arr[np.newaxis, :, :]
    if arr.ndim == 3:
        return arr
    if arr.ndim == 4 and arr.shape[-1] in (1, 2, 3, 4):
        return arr[..., 0]
    raise ValueError(f"Expected movie shaped T x Y x X, got {arr.shape} from {path}")


def stat_mask(roi: object, shape_yx: tuple[int, int]) -> tuple[np.ndarray, np.ndarray]:
    mask = np.zeros(shape_yx, dtype=bool)
    weights = np.array([], dtype=np.float32)
    if not isinstance(roi, dict):
        return mask, weights
    ypix = np.asarray(roi.get("ypix", []), dtype=int)
    xpix = np.asarray(roi.get("xpix", []), dtype=int)
    valid = (ypix >= 0) & (ypix < shape_yx[0]) & (xpix >= 0) & (xpix < shape_yx[1])
    ypix = ypix[valid]
    xpix = xpix[valid]
    if len(ypix) == 0:
        return mask, weights
    mask[ypix, xpix] = True
    lam = np.asarray(roi.get("lam", []), dtype=np.float32)
    if len(lam) == len(valid):
        lam = lam[valid]
    if len(lam) != len(ypix) or not np.isfinite(lam).any() or float(np.nansum(lam)) <= 0:
        weights = np.ones(len(ypix), dtype=np.float32)
    else:
        weights = lam.astype(np.float32, copy=False)
    return mask, weights


def mean_trace_from_mask(movie: np.ndarray, mask: np.ndarray, weights: np.ndarray | None = None) -> np.ndarray:
    if not np.any(mask):
        return np.full((movie.shape[0],), np.nan, dtype=np.float32)
    pixels = np.asarray(movie[:, mask], dtype=np.float32)
    if weights is not None and len(weights) == pixels.shape[1]:
        total = float(np.nansum(weights))
        if total > 0:
            return np.asarray(np.nansum(pixels * weights[np.newaxis, :], axis=1) / total, dtype=np.float32)
    return np.asarray(np.nanmean(pixels, axis=1), dtype=np.float32)


def neuropil_mask(
    roi_mask: np.ndarray,
    all_roi_mask: np.ndarray,
    inner_radius: int,
    outer_radius: int,
    min_pixels: int,
) -> np.ndarray:
    try:
        from scipy import ndimage as ndi
    except Exception:
        ypix, xpix = np.where(roi_mask)
        out = np.zeros_like(roi_mask, dtype=bool)
        if len(ypix) == 0:
            return out
        y0 = max(0, int(ypix.min()) - outer_radius)
        y1 = min(roi_mask.shape[0], int(ypix.max()) + outer_radius + 1)
        x0 = max(0, int(xpix.min()) - outer_radius)
        x1 = min(roi_mask.shape[1], int(xpix.max()) + outer_radius + 1)
        out[y0:y1, x0:x1] = True
        out &= ~all_roi_mask
        return out

    inner_radius = max(1, int(inner_radius))
    outer_radius = max(inner_radius + 1, int(outer_radius))
    inner = ndi.binary_dilation(roi_mask, iterations=inner_radius)
    outer = ndi.binary_dilation(roi_mask, iterations=outer_radius)
    ring = outer & ~inner & ~all_roi_mask
    if int(np.count_nonzero(ring)) >= min_pixels:
        return ring

    expanded = ndi.binary_dilation(roi_mask, iterations=outer_radius * 2)
    ring = expanded & ~inner & ~all_roi_mask
    return ring


def extract_traces_from_corrected_movie(
    movie_path: Path,
    stat: np.ndarray,
    selected: np.ndarray,
    neuropil_inner_radius: int,
    neuropil_outer_radius: int,
    min_neuropil_pixels: int,
) -> tuple[np.ndarray, np.ndarray]:
    movie = movie_as_tyx(movie_path)
    shape_yx = tuple(movie.shape[-2:])
    roi_masks: list[np.ndarray] = []
    roi_weights: list[np.ndarray] = []
    all_roi_mask = np.zeros(shape_yx, dtype=bool)

    for suite2p_idx in selected:
        mask, weights = stat_mask(stat[int(suite2p_idx)], shape_yx)
        roi_masks.append(mask)
        roi_weights.append(weights)
        all_roi_mask |= mask

    f_rows = []
    fneu_rows = []
    for mask, weights in zip(roi_masks, roi_weights):
        f_rows.append(mean_trace_from_mask(movie, mask, weights))
        nmask = neuropil_mask(
            roi_mask=mask,
            all_roi_mask=all_roi_mask,
            inner_radius=neuropil_inner_radius,
            outer_radius=neuropil_outer_radius,
            min_pixels=min_neuropil_pixels,
        )
        fneu_rows.append(mean_trace_from_mask(movie, nmask, None))

    return np.vstack(f_rows).astype(np.float32), np.vstack(fneu_rows).astype(np.float32)


def first_stim_start_sec(stim_events: pd.DataFrame) -> float | None:
    if stim_events.empty or "start_time_sec" not in stim_events.columns:
        return None
    values = pd.to_numeric(stim_events["start_time_sec"], errors="coerce").dropna()
    if values.empty:
        return None
    first = float(values.min())
    return first if first >= 0 else None


def compute_f0(
    f_corrected: np.ndarray,
    fps: float,
    stim_events: pd.DataFrame,
    f0_mode: str,
    f0_percentile: float,
    f0_window_sec: float,
    default_baseline_sec: float,
    min_baseline_frames: int,
) -> tuple[np.ndarray, dict]:
    info = {
        "f0_mode": f0_mode,
        "f0_percentile": float(f0_percentile),
        "f0_window_sec": float(f0_window_sec),
    }

    if f0_mode == "percentile":
        f0 = np.percentile(f_corrected, f0_percentile, axis=1, keepdims=True)
        return f0.astype(np.float32), info

    if f0_mode == "stim-baseline":
        start_sec = first_stim_start_sec(stim_events)
        if start_sec is None:
            baseline_frames = int(round(default_baseline_sec * fps))
        else:
            baseline_frames = int(np.floor(start_sec * fps))
        baseline_frames = min(max(baseline_frames, min_baseline_frames), f_corrected.shape[1])
        baseline = f_corrected[:, :baseline_frames]
        f0 = np.percentile(baseline, f0_percentile, axis=1, keepdims=True)
        info.update({"baseline_frames": int(baseline_frames), "first_stim_start_sec": start_sec})
        return f0.astype(np.float32), info

    window = max(1, int(round(f0_window_sec * fps)))
    rows = []
    for trace in f_corrected:
        series = pd.Series(trace)
        if f0_mode == "rolling-percentile":
            rows.append(
                series.rolling(window=window, center=True, min_periods=1)
                .quantile(f0_percentile / 100.0)
                .to_numpy(dtype=np.float32)
            )
        elif f0_mode == "rolling-median":
            rows.append(
                series.rolling(window=window, center=True, min_periods=1)
                .median()
                .to_numpy(dtype=np.float32)
            )
        else:
            raise ValueError(f"Unsupported f0_mode: {f0_mode}")
    info["rolling_window_frames"] = int(window)
    return np.vstack(rows).astype(np.float32), info


def compute_dff(f_corrected: np.ndarray, f0: np.ndarray, eps: float) -> np.ndarray:
    denominator = np.maximum(np.abs(f0), eps)
    return ((f_corrected - f0) / denominator).astype(np.float32)


def stat_xy(roi) -> tuple[float, float, int]:
    if not isinstance(roi, dict):
        return np.nan, np.nan, 0
    xpix = np.asarray(roi.get("xpix", []), dtype=float)
    ypix = np.asarray(roi.get("ypix", []), dtype=float)
    if len(xpix) and len(ypix):
        return float(np.mean(xpix)), float(np.mean(ypix)), int(len(xpix))
    med = roi.get("med", [np.nan, np.nan])
    y_mean = safe_float(med[0] if len(med) > 0 else None, np.nan)
    x_mean = safe_float(med[1] if len(med) > 1 else None, np.nan)
    return float(x_mean), float(y_mean), 0


def safe_int(value, default: int = -1) -> int:
    try:
        if value is None:
            return default
        out = int(value)
        return out
    except Exception:
        return default


def stat_roi_metadata(roi: object, stat_index: int) -> dict:
    if not isinstance(roi, dict):
        return {
            "roi_source": "suite2p",
            "roi_type": "suite2p",
            "manual_roi_id": -1,
            "suite2p_original_id": int(stat_index),
            "previous_suite2p_original_id": -1,
            "source_roi_id": f"suite2p_{int(stat_index)}",
        }

    roi_source = str(roi.get("roi_source", "") or "").strip()
    if roi_source in {"suite2p_reference", "suite2p"} or (not roi_source and "manual_roi_id" not in roi):
        suite2p_id = safe_int(roi.get("suite2p_original_id"), int(stat_index))
        return {
            "roi_source": "suite2p",
            "roi_type": str(roi.get("roi_type", "suite2p") or "suite2p"),
            "manual_roi_id": -1,
            "suite2p_original_id": suite2p_id,
            "previous_suite2p_original_id": -1,
            "source_roi_id": str(roi.get("source_roi_id", f"suite2p_{suite2p_id}") or f"suite2p_{suite2p_id}"),
        }

    manual_id = safe_int(roi.get("manual_roi_id"), int(stat_index) + 1)
    previous_suite2p_id = safe_int(roi.get("previous_suite2p_original_id"), -1)
    if previous_suite2p_id < 0:
        previous_suite2p_id = safe_int(roi.get("suite2p_original_id"), -1)
    return {
        "roi_source": "manual",
        "roi_type": str(roi.get("roi_type", "manual") or "manual"),
        "manual_roi_id": manual_id,
        "suite2p_original_id": -1,
        "previous_suite2p_original_id": previous_suite2p_id,
        "source_roi_id": str(roi.get("source_roi_id", f"manual_{manual_id}") or f"manual_{manual_id}"),
    }


def build_roi_table(
    trial_id: str,
    selected: np.ndarray,
    iscell_flag: np.ndarray,
    iscell_prob: np.ndarray,
    stat: np.ndarray,
    f_raw: np.ndarray,
    fneu: np.ndarray,
    f_corrected: np.ndarray,
    f0: np.ndarray,
    dff: np.ndarray,
) -> pd.DataFrame:
    rows = []
    f0_stat = f0 if f0.shape == dff.shape else np.repeat(f0, dff.shape[1], axis=1)
    for out_idx, stat_idx in enumerate(selected):
        roi_stat = stat[int(stat_idx)]
        x_mean, y_mean, npix = stat_xy(roi_stat)
        metadata = stat_roi_metadata(roi_stat, int(stat_idx))
        trace = dff[out_idx]
        std_dff = float(np.nanstd(trace))
        max_dff = float(np.nanmax(trace))
        rows.append(
            {
                "trial_id": trial_id,
                "roi_id": out_idx + 1,
                "source_roi_id": metadata["source_roi_id"],
                "roi_source": metadata["roi_source"],
                "roi_type": metadata["roi_type"],
                "manual_roi_id": metadata["manual_roi_id"],
                "suite2p_original_id": metadata["suite2p_original_id"],
                "previous_suite2p_original_id": metadata["previous_suite2p_original_id"],
                "stat_index": int(stat_idx),
                "iscell": int(bool(iscell_flag[stat_idx])),
                "iscell_prob": float(iscell_prob[stat_idx]) if np.isfinite(iscell_prob[stat_idx]) else np.nan,
                "x_mean": x_mean,
                "y_mean": y_mean,
                "npix": npix,
                "mean_F": float(np.nanmean(f_raw[out_idx])),
                "mean_Fneu": float(np.nanmean(fneu[out_idx])),
                "mean_F_corrected": float(np.nanmean(f_corrected[out_idx])),
                "mean_F0": float(np.nanmean(f0_stat[out_idx])),
                "mean_dff": float(np.nanmean(trace)),
                "std_dff": std_dff,
                "max_dff": max_dff,
                "snr_like": float(max_dff / std_dff) if std_dff > 0 else np.nan,
            }
        )
    return pd.DataFrame(rows)


def write_dff_traces_csv(path: Path, dff: np.ndarray, fps: float) -> None:
    n_roi, n_frames = dff.shape
    fieldnames = ["frame", "time_sec"] + [f"roi_{i + 1:04d}" for i in range(n_roi)]
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(fieldnames)
        for frame in range(n_frames):
            writer.writerow([frame, frame / fps, *dff[:, frame].tolist()])


def stim_spans(stim_events: pd.DataFrame) -> list[tuple[float, float]]:
    if stim_events.empty or "start_time_sec" not in stim_events.columns:
        return []
    spans = []
    for _, row in stim_events.iterrows():
        start = safe_float(row.get("start_time_sec"), None)
        if start is None:
            continue
        end = safe_float(row.get("end_time_sec"), None)
        duration = safe_float(row.get("duration_sec"), None)
        if end is None and duration is not None:
            end = start + duration
        if end is None or end < start:
            end = start
        spans.append((float(start), float(end)))
    return spans


def mark_stimuli(ax, stim_events: pd.DataFrame) -> None:
    for start, end in stim_spans(stim_events):
        if end > start:
            ax.axvspan(start, end, color="tab:orange", alpha=0.16, lw=0)
        else:
            ax.axvline(start, color="tab:orange", alpha=0.35, lw=0.8)


def save_dff_heatmap(
    dff: np.ndarray,
    fps: float,
    stim_events: pd.DataFrame,
    output_path: Path,
    trial_id: str,
    max_rois: int,
    dpi: int,
) -> None:
    import matplotlib.pyplot as plt

    if dff.size == 0:
        return
    heatmap = dff
    if max_rois > 0 and dff.shape[0] > max_rois:
        keep = np.argsort(np.nanmax(dff, axis=1))[::-1][:max_rois]
        heatmap = dff[keep]
    finite = heatmap[np.isfinite(heatmap)]
    vmin = float(np.nanpercentile(finite, 2)) if finite.size else -1.0
    vmax = float(np.nanpercentile(finite, 98)) if finite.size else 2.0
    if vmax <= vmin:
        vmax = vmin + 1e-6

    fig, ax = plt.subplots(figsize=(12, 6))
    im = ax.imshow(
        heatmap,
        aspect="auto",
        interpolation="nearest",
        cmap="viridis",
        extent=[0, heatmap.shape[1] / fps, heatmap.shape[0], 0],
        vmin=vmin,
        vmax=vmax,
    )
    mark_stimuli(ax, stim_events)
    ax.set_xlabel("Time (s)")
    ax.set_ylabel("ROI")
    ax.set_title(f"dF/F heatmap - {trial_id}")
    fig.colorbar(im, ax=ax, label="dF/F")
    plt.tight_layout()
    try:
        fig.savefig(output_path, dpi=dpi, bbox_inches="tight")
        fig.savefig(output_path.with_suffix(".pdf"), bbox_inches="tight")
    finally:
        plt.close(fig)


def choose_example_rois(roi_table: pd.DataFrame, n_roi: int, seed: int) -> list[int]:
    if n_roi <= 0:
        return []
    choices: list[int] = []
    if "max_dff" in roi_table:
        choices.append(int(pd.to_numeric(roi_table["max_dff"], errors="coerce").idxmax()))
    if "snr_like" in roi_table:
        snr = pd.to_numeric(roi_table["snr_like"], errors="coerce")
        if snr.notna().any():
            choices.append(int(snr.idxmax()))
    choices.append(int(np.random.default_rng(seed).integers(0, n_roi)))
    out = []
    for idx in choices:
        if 0 <= idx < n_roi and idx not in out:
            out.append(idx)
    return out


def save_example_traces(
    dff: np.ndarray,
    roi_table: pd.DataFrame,
    fps: float,
    stim_events: pd.DataFrame,
    output_path: Path,
    trial_id: str,
    seed: int,
    dpi: int,
) -> None:
    import matplotlib.pyplot as plt

    indices = choose_example_rois(roi_table, dff.shape[0], seed=seed)
    if not indices:
        return
    time_axis = np.arange(dff.shape[1]) / fps
    fig, axes = plt.subplots(len(indices), 1, figsize=(12, max(3, 1.9 * len(indices))), sharex=True)
    if len(indices) == 1:
        axes = [axes]
    for ax, idx in zip(axes, indices):
        mark_stimuli(ax, stim_events)
        ax.plot(time_axis, dff[idx], lw=0.9, color="tab:blue")
        row = roi_table.iloc[idx]
        roi_source = str(row.get("roi_source", "suite2p"))
        if roi_source == "manual":
            source_label = f"manual {int(row.get('manual_roi_id', row['roi_id']))}"
        else:
            source_label = f"s2p {int(row.get('suite2p_original_id', idx))}"
        ax.set_ylabel(
            f"ROI {int(row['roi_id'])}\n{source_label}",
            rotation=0,
            labelpad=36,
            va="center",
        )
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
    axes[-1].set_xlabel("Time (s)")
    fig.suptitle(f"Example dF/F traces - {trial_id}", y=0.995)
    plt.tight_layout()
    try:
        fig.savefig(output_path, dpi=dpi, bbox_inches="tight")
        fig.savefig(output_path.with_suffix(".pdf"), bbox_inches="tight")
    finally:
        plt.close(fig)


def process_trial(trial: TrialInput, out_dir: Path, args: argparse.Namespace) -> tuple[str, dict]:
    out_dir.mkdir(parents=True, exist_ok=True)
    copy_sidecar_outputs(trial, out_dir)

    suite2p_f_all, suite2p_fneu_all, suite2p_iscell, suite2p_stat, ops = load_suite2p_inputs(trial)
    f_all = suite2p_f_all
    fneu_all = suite2p_fneu_all
    iscell = suite2p_iscell
    stat = suite2p_stat
    manual_source_path = None

    manual_inputs = None
    if args.roi_source in ("auto", "manual"):
        manual_inputs = load_manual_roi_inputs(args.manual_root, trial)
        if manual_inputs is None and args.roi_source == "manual":
            raise FileNotFoundError(f"Requested manual ROI source but no manual compatible output was found for {trial.trial_id}")
    if manual_inputs is not None:
        stat, iscell, manual_f, manual_fneu, manual_source_path = manual_inputs
        if manual_f is not None and manual_fneu is not None and manual_f.shape == manual_fneu.shape:
            f_all = manual_f
            fneu_all = manual_fneu
        else:
            n_frames = suite2p_f_all.shape[1]
            f_all = np.full((len(stat), n_frames), np.nan, dtype=np.float32)
            fneu_all = np.full((len(stat), n_frames), np.nan, dtype=np.float32)

    selected, iscell_flag, iscell_prob, roi_source_used, roi_source_path = select_rois(
        iscell,
        include_noncell=args.include_noncell,
        roi_source=args.roi_source,
    )
    if manual_inputs is not None:
        roi_source_used = "manual_curation"
        roi_source_path = manual_source_path
    if len(selected) == 0:
        return "failed", {"trial_id": trial.trial_id, "status": "failed", "message": "No ROI selected after ROI filtering"}

    meta = load_json(trial.metadata_path)
    stim_events = read_csv_if_exists(trial.stim_events_path)
    fps = get_fps_from_metadata(meta, ops=ops, default_fps=args.default_fps)

    trace_movie_path = None
    if args.trace_source == "motion-corrected":
        trace_movie_path = corrected_movie_path(args.data_root, trial, args.trace_movie_root)
        if trace_movie_path is None:
            raise FileNotFoundError(
                f"Could not find motion-corrected movie for {trial.trial_id}. "
                "Use --trace-source suite2p to fall back to suite2p F.npy/Fneu.npy."
            )
        f_raw, fneu = extract_traces_from_corrected_movie(
            movie_path=trace_movie_path,
            stat=stat,
            selected=selected,
            neuropil_inner_radius=args.neuropil_inner_radius,
            neuropil_outer_radius=args.neuropil_outer_radius,
            min_neuropil_pixels=args.min_neuropil_pixels,
        )
        trace_source_used = "motion_corrected_movie"
        neuropil_source = "local_annulus_from_motion_corrected_movie"
    else:
        f_raw = f_all[selected]
        fneu = fneu_all[selected]
        trace_source_used = "manual_or_suite2p_F.npy" if manual_inputs is not None else "suite2p_F.npy"
        neuropil_source = "manual_or_suite2p_Fneu.npy" if manual_inputs is not None else "suite2p_Fneu.npy"

    f_corrected = (f_raw - args.neuropil_coeff * fneu).astype(np.float32)
    f0, f0_info = compute_f0(
        f_corrected=f_corrected,
        fps=fps,
        stim_events=stim_events,
        f0_mode=args.f0_mode,
        f0_percentile=args.f0_percentile,
        f0_window_sec=args.f0_window_sec,
        default_baseline_sec=args.default_baseline_sec,
        min_baseline_frames=args.min_baseline_frames,
    )
    dff = compute_dff(f_corrected, f0=f0, eps=args.f0_eps)

    np.save(out_dir / f"{trial.trial_id}_F_raw.npy", f_raw)
    np.save(out_dir / f"{trial.trial_id}_Fneu.npy", fneu)
    np.save(out_dir / f"{trial.trial_id}_F_corrected.npy", f_corrected)
    np.save(out_dir / f"{trial.trial_id}_F0.npy", f0)
    np.save(out_dir / f"{trial.trial_id}_dff.npy", dff)

    roi_table = build_roi_table(
        trial_id=trial.trial_id,
        selected=selected,
        iscell_flag=iscell_flag,
        iscell_prob=iscell_prob,
        stat=stat,
        f_raw=f_raw,
        fneu=fneu,
        f_corrected=f_corrected,
        f0=f0,
        dff=dff,
    )
    roi_table.to_csv(out_dir / f"{trial.trial_id}_roi_table.csv", index=False)
    write_dff_traces_csv(out_dir / f"{trial.trial_id}_dff_traces.csv", dff=dff, fps=fps)

    summary = {
        "trial_id": trial.trial_id,
        "status": "ok",
        "n_suite2p_roi_total": int(suite2p_f_all.shape[0]),
        "n_roi_total": int(len(stat)),
        "n_roi_selected": int(len(selected)),
        "n_frames": int(dff.shape[1]),
        "fps": float(fps),
        "duration_sec": float(dff.shape[1] / fps),
        "include_noncell": bool(args.include_noncell),
        "roi_source_requested": args.roi_source,
        "roi_source_used": roi_source_used,
        "roi_source_path": roi_source_path,
        "trace_source": trace_source_used,
        "trace_movie_path": str(trace_movie_path) if trace_movie_path is not None else None,
        "neuropil_source": neuropil_source,
        "neuropil_coeff": float(args.neuropil_coeff),
        "f0_eps": float(args.f0_eps),
        "mean_dff": float(np.nanmean(dff)),
        "max_dff": float(np.nanmax(dff)),
        "mean_snr_like": float(pd.to_numeric(roi_table["snr_like"], errors="coerce").mean()),
        "metadata_path": str(trial.metadata_path) if trial.metadata_path else None,
        "stim_events_path": str(trial.stim_events_path) if trial.stim_events_path else None,
        "suite2p_plane0": str(trial.plane0_dir),
        "manual_root": str(args.manual_root),
        **f0_info,
    }
    pd.DataFrame([summary]).to_csv(out_dir / f"{trial.trial_id}_dff_summary.csv", index=False)

    save_dff_heatmap(
        dff=dff,
        fps=fps,
        stim_events=stim_events,
        output_path=out_dir / f"{trial.trial_id}_dff_heatmap.png",
        trial_id=trial.trial_id,
        max_rois=args.heatmap_max_rois,
        dpi=args.dpi,
    )
    save_example_traces(
        dff=dff,
        roi_table=roi_table,
        fps=fps,
        stim_events=stim_events,
        output_path=out_dir / f"{trial.trial_id}_example_traces.png",
        trial_id=trial.trial_id,
        seed=args.random_seed,
        dpi=args.dpi,
    )

    selected_records = roi_table[
        [
            "roi_id",
            "source_roi_id",
            "roi_source",
            "roi_type",
            "manual_roi_id",
            "suite2p_original_id",
            "previous_suite2p_original_id",
            "stat_index",
        ]
    ].to_dict(orient="records")
    with (out_dir / f"{trial.trial_id}_dff_summary.json").open("w", encoding="utf-8") as handle:
        json.dump(
            {
                **summary,
                "selected_roi_records": selected_records,
                "selected_suite2p_indices": [
                    int(value)
                    for value in roi_table["suite2p_original_id"].tolist()
                    if pd.notna(value) and int(value) >= 0
                ],
            },
            handle,
            indent=2,
        )
    return "processed", summary


